# ---------------------------------------------------------
# Python Variables and Data Types
# ---------------------------------------------------------

# Create variables with different data types
x = 10
y = 10.6
z = x + y

# Display the type of variable x
print("X:", type(x))

# Display the type of variable y
print("Y:", type(y))

# Display the value of z
print("Z:", z)

# Display the type of variable z
print("Z:", type(z))


# ---------------------------------------------------------
# String to Integer Conversion
# ---------------------------------------------------------

# Store a number as a string
s = "100"

# Convert string into integer
a = int(s)

# Display the original string
print(s)

# Display the converted integer
print(a)

# Display the data type of converted value
print(type(a))


# ---------------------------------------------------------
# Integer to Float Conversion
# ---------------------------------------------------------

# Store an integer value
num_int = 25

# Convert integer into float
num_float = float(num_int)

# Display integer value and its type
print("Integer Value:", num_int, "Type:", type(num_int))

# Display converted float value and its type
print("Converted to Float:", num_float, "Type:", type(num_float))


# ---------------------------------------------------------
# Float to String Conversion
# ---------------------------------------------------------

# Store a float value
price = 99.99

# Convert float into string
price_str = str(price)

# Display float value and its type
print("\nFloat Value:", price, "Type:", type(price))

# Display converted string value and its type
print("Converted to String:", price_str, "Type:", type(price_str))


